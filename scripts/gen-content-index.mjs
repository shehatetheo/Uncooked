// Builds content/index.gen.ts from the files on disk, so adding a problem,
// SQL problem, quiz file or card file means adding exactly one file.
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "content");
const groups = ["problems", "sql", "quiz", "cards"];
mkdirSync(join(root, "gen"), { recursive: true });
for (const g of groups) {
  const dir = join(root, g);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ts")).sort() : [];
  const imports = files.map((f, i) => `import c${i} from "../${g}/${f.replace(/\.ts$/, "")}";`).join("\n");
  // one module per kind, so a page only bundles the content it uses
  writeFileSync(join(root, "gen", `${g}.ts`), `// GENERATED by scripts/gen-content-index.mjs. Do not edit.\n${imports}\n\nexport default [${files.map((_, i) => `c${i}`).join(", ")}];\n`);
}

// Generated art and clips: a file named after a problem id in public/art or
// public/clips is picked up automatically.
const pub = join(root, "..", "public");
const scan = (dir) => (existsSync(join(pub, dir)) ? readdirSync(join(pub, dir)).filter((f) => !f.startsWith(".")).sort() : []);
const entries = (dir) => scan(dir).map((f) => `  "${f.replace(/\.[^.]+$/, "")}": "/${dir}/${f}",`).join("\n");
writeFileSync(
  join(root, "gen", "media.ts"),
  `// GENERATED by scripts/gen-content-index.mjs. Do not edit.\nexport const ART: Record<string, string> = {\n${entries("art")}\n};\nexport const CLIPS: Record<string, string> = {\n${entries("clips")}\n};\n/** Recorded interviewer audio: <id>.mp3 (question) and <id>-say.mp3 (model answer). */\nexport const VOICE: Record<string, string> = {\n${entries("voice")}\n};\n`,
);
console.log("content index generated");
