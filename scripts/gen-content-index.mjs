// Builds content/index.gen.ts from the files on disk, so adding a problem,
// SQL problem, quiz file or card file means adding exactly one file.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "content");
const groups = ["problems", "sql", "quiz", "cards"];
let imports = "";
let exports = "";
for (const g of groups) {
  const dir = join(root, g);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ts")).sort() : [];
  const names = files.map((f, i) => {
    imports += `import ${g}${i} from "./${g}/${f.replace(/\.ts$/, "")}";\n`;
    return `${g}${i}`;
  });
  exports += `export const ${g}Raw = [${names.join(", ")}];\n`;
}
writeFileSync(join(root, "index.gen.ts"), `// GENERATED by scripts/gen-content-index.mjs. Do not edit.\n${imports}\n${exports}`);

// Generated art and clips: a file named after a problem id in public/art or
// public/clips is picked up automatically.
const pub = join(root, "..", "public");
const scan = (dir) => (existsSync(join(pub, dir)) ? readdirSync(join(pub, dir)).filter((f) => !f.startsWith(".")).sort() : []);
const entries = (dir) => scan(dir).map((f) => `  "${f.replace(/\.[^.]+$/, "")}": "/${dir}/${f}",`).join("\n");
writeFileSync(
  join(root, "media.gen.ts"),
  `// GENERATED by scripts/gen-content-index.mjs. Do not edit.\nexport const ART: Record<string, string> = {\n${entries("art")}\n};\nexport const CLIPS: Record<string, string> = {\n${entries("clips")}\n};\n`,
);
console.log("content index generated");
